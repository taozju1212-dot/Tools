/* ---------- 帧缓存 ---------- */
static uint8_t g_fb[OLED_PAGES][OLED_W];
static uint8_t g_fb_dirty[OLED_PAGES];

/* ============================================================================
 *  I2C 底层（使用 BSP 已初始化的 I2C1 硬件外设）
 * ============================================================================ */

static void I2C_WaitBusy(void)
{
    uint32_t timeout = 10000;
    while (I2C_GetFlagStatus(I2C1, I2C_FLAG_BUSY) && timeout--);
}

static void I2C_WaitEvent(uint32_t event)
{
    uint32_t timeout = 10000;
    while (!I2C_CheckEvent(I2C1, event) && timeout--);
}

static void OLED_WriteCmd(uint8_t cmd)
{
    I2C_WaitBusy();
    I2C_GenerateSTART(I2C1, ENABLE);
    I2C_WaitEvent(I2C_EVENT_MASTER_MODE_SELECT);
    I2C_Send7bitAddress(I2C1, OLED_ADDR, I2C_Direction_Transmitter);
    I2C_WaitEvent(I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED);
    I2C_SendData(I2C1, 0x00);           /* control byte: command */
    I2C_WaitEvent(I2C_EVENT_MASTER_BYTE_TRANSMITTED);
    I2C_SendData(I2C1, cmd);
    I2C_WaitEvent(I2C_EVENT_MASTER_BYTE_TRANSMITTED);
    I2C_GenerateSTOP(I2C1, ENABLE);
}

static void OLED_WritePage(uint8_t page, const uint8_t *data)
{
    uint8_t i;
    I2C_WaitBusy();
    I2C_GenerateSTART(I2C1, ENABLE);
    I2C_WaitEvent(I2C_EVENT_MASTER_MODE_SELECT);
    I2C_Send7bitAddress(I2C1, OLED_ADDR, I2C_Direction_Transmitter);
    I2C_WaitEvent(I2C_EVENT_MASTER_TRANSMITTER_MODE_SELECTED);
    I2C_SendData(I2C1, 0x40);           /* control byte: data */
    I2C_WaitEvent(I2C_EVENT_MASTER_BYTE_TRANSMITTED);
    for (i = 0; i < OLED_W; i++) {
        I2C_SendData(I2C1, data[i]);
        I2C_WaitEvent(I2C_EVENT_MASTER_BYTE_TRANSMITTED);
    }
    I2C_GenerateSTOP(I2C1, ENABLE);
    (void)page;
}

static void OLED_SetCursor(uint8_t page, uint8_t col)
{
    col += OLED_COL_OFFSET;
    OLED_WriteCmd(0xB0 | page);
    OLED_WriteCmd(0x00 | (col & 0x0F));
    OLED_WriteCmd(0x10 | (col >> 4));
}

/* ============================================================================
 *  初始化序列（SH1106/SSD1306 兼容）
 * ============================================================================ */
void OLED_Init(void)
{
    uint8_t i;
    static const uint8_t init_seq[] = {
        0xAE,       /* display off */
        0xD5, 0x80, /* clock div: reset ratio, max freq */
        0xA8, 0x3F, /* multiplex 1/64 */
        0xD3, 0x00, /* display offset 0 */
        0x40,       /* start line 0 */
        0xAD, 0x8B, /* internal DC-DC on (SH1106) */
        0xA1,       /* segment remap: col127=SEG0 */
        0xC8,       /* COM scan: remapped */
        0xDA, 0x12, /* COM pins: alternative */
        0x81, 0xA0, /* contrast */
        0xD9, 0x22, /* pre-charge */
        0xDB, 0x35, /* VCOMH */
        0xA4,       /* entire display: follow RAM */
        0xA6,       /* normal (not inverted) */
        0xAF,       /* display on */
    };
    for (i = 0; i < sizeof(init_seq); i++)
        OLED_WriteCmd(init_seq[i]);

    OLED_Clear();
}

void OLED_Clear(void)
{
    memset(g_fb, 0, sizeof(g_fb));
    memset(g_fb_dirty, 1, sizeof(g_fb_dirty));
    OLED_Flush();
}

void OLED_MarkDirty(void)
{
    memset(g_fb_dirty, 1, sizeof(g_fb_dirty));
}

void OLED_Flush(void)
{
    uint8_t p;
    for (p = 0; p < OLED_PAGES; p++) {
        if (!g_fb_dirty[p]) continue;
        OLED_SetCursor(p, 0);
        OLED_WritePage(p, g_fb[p]);
        g_fb_dirty[p] = 0;
    }
}

/* ============================================================================
 *  帧缓存像素操作
 * ============================================================================ */
void FB_SetPixel(uint8_t x, uint8_t y)
{
    if (x >= OLED_W || y >= OLED_H) return;
    g_fb[y >> 3][x] |=  (uint8_t)(1 << (y & 7));
    g_fb_dirty[y >> 3] = 1;
}

void FB_ClrPixel(uint8_t x, uint8_t y)
{
    if (x >= OLED_W || y >= OLED_H) return;
    g_fb[y >> 3][x] &= (uint8_t)~(1 << (y & 7));
    g_fb_dirty[y >> 3] = 1;
}

void FB_FillRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t fill)
{
    uint8_t row;
    uint8_t col;
    for (row = y; row < y + h; row++)
        for (col = x; col < x + w; col++) {
            if (fill) FB_SetPixel(col, row);
            else      FB_ClrPixel(col, row);
        }
}

void FB_DrawRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t thick)
{
    uint8_t t;
    uint8_t col;
    uint8_t row;
    for (t = 0; t < thick; t++) {
        for (col = x+t; col < x+w-t; col++) {
            FB_SetPixel(col, y+t);
            FB_SetPixel(col, y+h-1-t);
        }
        for (row = y+t; row < y+h-t; row++) {
            FB_SetPixel(x+t, row);
            FB_SetPixel(x+w-1-t, row);
        }
    }
}

