/* ============================================================================
 *  编辑态值闪烁 —— 仅清/绘 value 区域（y=10..25），其余像素保持
 *  on=1 显示值, on=0 隐藏值，外层 500ms 节拍切换
 * ============================================================================ */
void UI_BlinkValue_Speed(uint8_t on)
{
    /* 左面板值区域 x=2..61 (60px), y=10..25 (16px) */
    FB_FillRect(2, 10, 60, 16, 0);
    if (on) {
        char buf[8];
        uint8_t n;
        uint8_t x;
        n = uint_to_str(g_draft_rpm, buf);
        x = (uint8_t)((64 - (uint8_t)(n * 8)) / 2);
        if (x < 2) x = 2;
        FB_DrawStr8x16(x, 10, buf);
    }
    /* 跨页 1(y=8..15) 和页 2(y=16..23) 和页 3(y=24..31, 仅 24,25 有变化) */
    g_fb_dirty[1] = 1;
    g_fb_dirty[2] = 1;
    g_fb_dirty[3] = 1;
    OLED_Flush();
}

void UI_BlinkValue_Cur(uint8_t on)
{
    /* 右面板值区域 x=68..123 (56px), y=10..25 */
    FB_FillRect(68, 10, 56, 16, 0);
    if (on) {
        char buf[8];
        uint8_t i = 0;
        uint8_t k;
        uint16_t ma10 = Irun_To_mA10(g_draft_irun);
        char tmp[8];
        uint8_t n = 0;
        uint8_t x;
        uint_to_str(ma10 / 10, tmp);
        for (k = 0; tmp[k]; k++) buf[i++] = tmp[k];
        buf[i++] = '.';
        buf[i++] = (char)('0' + (ma10 % 10));
        buf[i] = '\0';
        while (buf[n]) n++;
        x = (uint8_t)(65 + (63 - (uint8_t)(n * 8)) / 2);
        FB_DrawStr8x16(x, 10, buf);
    }
    g_fb_dirty[1] = 1;
    g_fb_dirty[2] = 1;
    g_fb_dirty[3] = 1;
    OLED_Flush();
}
