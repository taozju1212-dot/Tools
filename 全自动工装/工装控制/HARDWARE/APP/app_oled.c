void UI_Render_Cal_Step2_OK(uint8_t agc, uint16_t led, uint8_t ref)
{
    char buf[6];
    uint8_t n;
    uint8_t cx;
    /* 3 列中心 x: AGC≈20, LED≈64, REF≈108 */
    static const uint8_t COL_CX[3] = {20, 64, 108};

    OLED_Clear();
    Draw_Outer_Frame();

    /* ---- 数值行 y=12 ---- */
    /* AGC */
    n = uint_to_str(agc, buf);
    cx = (uint8_t)(COL_CX[0] - (uint8_t)(n * 8) / 2);
    FB_DrawStr8x16(cx, 12, buf);
    /* LED */
    n = uint_to_str(led, buf);
    cx = (uint8_t)(COL_CX[1] - (uint8_t)(n * 8) / 2);
    FB_DrawStr8x16(cx, 12, buf);
    /* REF */
    n = uint_to_str(ref, buf);
    cx = (uint8_t)(COL_CX[2] - (uint8_t)(n * 8) / 2);
    FB_DrawStr8x16(cx, 12, buf);

    /* ---- 标签行 y=36：每个 3 字符宽 24px，居中于列中心 ---- */
    FB_DrawStr8x16((uint8_t)(COL_CX[0] - 12), 36, "AGC");
    FB_DrawStr8x16((uint8_t)(COL_CX[1] - 12), 36, "LED");
    FB_DrawStr8x16((uint8_t)(COL_CX[2] - 12), 36, "REF");

    OLED_MarkDirty();
    OLED_Flush();
}

