/* ============================================================================
 *  字符渲染
 * ============================================================================ */
void FB_DrawChar8x16(uint8_t x, uint8_t y, char c)
{
    const uint8_t *bmp;
    uint8_t row;
    if (c < 32 || c > 126) c = 32;
    bmp = g_font8x16[c - 32];
    for (row = 0; row < 16; row++) {
        uint8_t bits = bmp[row];
        uint8_t col;
        for (col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) FB_SetPixel(x + col, y + row);
            else                       FB_ClrPixel(x + col, y + row);
        }
    }
}

void FB_DrawStr8x16(uint8_t x, uint8_t y, const char *s)
{
    while (*s) {
        FB_DrawChar8x16(x, y, *s++);
        x += 8;
    }
}

void FB_DrawCJK(uint8_t x, uint8_t y, uint8_t idx)
{
    const uint8_t *bmp;
    uint8_t row;
    if (idx >= CJK_CHAR_COUNT) return;
    bmp = g_cjk16x16[idx];
    for (row = 0; row < 16; row++) {
        uint16_t bits = ((uint16_t)bmp[row * 2] << 8) | bmp[row * 2 + 1];
        uint8_t col;
        for (col = 0; col < 16; col++) {
            if (bits & (0x8000U >> col)) FB_SetPixel(x + col, y + row);
            else                          FB_ClrPixel(x + col, y + row);
        }
    }
}

void FB_DrawCJKStr(uint8_t x, uint8_t y, const uint8_t *idx_arr, uint8_t cnt)
{
    uint8_t i;
    for (i = 0; i < cnt; i++) {
        FB_DrawCJK(x, y, idx_arr[i]);
        x += 16;
    }
}

/* ============================================================================
 *  数值格式化 (纯整数, 无 printf/sprintf)
 * ============================================================================ */
static uint8_t uint_to_str(uint32_t v, char *buf)  /* 返回字符串长度 */
{
    char tmp[10];
    uint8_t n = 0;
    uint8_t i;
    if (v == 0) { buf[0] = '0'; buf[1] = '\0'; return 1; }
    while (v) { tmp[n++] = (char)('0' + (v % 10)); v /= 10; }
    for (i = 0; i < n; i++) buf[i] = tmp[n - 1 - i];
    buf[n] = '\0';
    return n;
}

/* 格式化 "N.N A" (Irun_To_mA10 返回 0.1A 单位) */
static void fmt_amp(char *buf, uint8_t irun)
{
    uint16_t ma10;
    char tmp[4];
    uint8_t i = 0;
    uint8_t k;
    ma10 = Irun_To_mA10(irun);
    uint_to_str(ma10 / 10, tmp);
    for (k = 0; tmp[k]; k++) buf[i++] = tmp[k];
    buf[i++] = '.';
    buf[i++] = (char)('0' + (ma10 % 10));
    buf[i++] = ' '; buf[i++] = 'A'; buf[i] = '\0';
}

/* ============================================================================
 *  圆形绘制（主界面光开关指示用）
 * ============================================================================ */

/* Bresenham 填充圆 */
static void FB_FillCircle(uint8_t cx, uint8_t cy, uint8_t r)
{
    int16_t x = (int16_t)r, y = 0, P = 1 - (int16_t)r;
    while (x >= y) {
        int16_t i;
        for (i = (int16_t)cx - x; i <= (int16_t)cx + x; i++) {
            if (i >= 0 && i < OLED_W) {
                if ((int16_t)cy + y >= 0 && (int16_t)cy + y < OLED_H)
                    FB_SetPixel((uint8_t)i, (uint8_t)((int16_t)cy + y));
                if ((int16_t)cy - y >= 0 && (int16_t)cy - y < OLED_H)
                    FB_SetPixel((uint8_t)i, (uint8_t)((int16_t)cy - y));
            }
        }
        for (i = (int16_t)cx - y; i <= (int16_t)cx + y; i++) {
            if (i >= 0 && i < OLED_W) {
                if ((int16_t)cy + x >= 0 && (int16_t)cy + x < OLED_H)
                    FB_SetPixel((uint8_t)i, (uint8_t)((int16_t)cy + x));
                if ((int16_t)cy - x >= 0 && (int16_t)cy - x < OLED_H)
                    FB_SetPixel((uint8_t)i, (uint8_t)((int16_t)cy - x));
            }
        }
        y++;
        if (P <= 0) P += 2 * y + 1;
        else        { x--; P += 2 * (y - x) + 1; }
    }
}

/* Bresenham 圆环 */
static void FB_DrawCircleRing(uint8_t cx, uint8_t cy, uint8_t r)
{
    int16_t x = (int16_t)r, y = 0, P = 1 - (int16_t)r;
    while (x >= y) {
#define _SP(a,b) do { \
    int16_t _px=(int16_t)cx+(a), _py=(int16_t)cy+(b); \
    if(_px>=0&&_px<OLED_W&&_py>=0&&_py<OLED_H) FB_SetPixel((uint8_t)_px,(uint8_t)_py); \
} while(0)
        _SP( x, y); _SP(-x, y); _SP( x,-y); _SP(-x,-y);
        _SP( y, x); _SP(-y, x); _SP( y,-x); _SP(-y,-x);
#undef _SP
        y++;
        if (P <= 0) P += 2 * y + 1;
        else        { x--; P += 2 * (y - x) + 1; }
    }
}

