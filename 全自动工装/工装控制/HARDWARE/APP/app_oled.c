    FB_FillRect(0, y, HOME_CARD_W, HOME_CARD_H, 0);

    /* 组合字符串 "M1-300R-1.1A" */
    buf[i++] = 'M';
    buf[i++] = (char)('0' + motor);
    buf[i++] = '-';
    uint_to_str(rpm, tmp);
    for (k = 0; tmp[k]; k++) buf[i++] = tmp[k];
